// The service worker of a content-free push: the source text of a script the app serves itself.
// Pure: the same options give the same text. The generated script never reads the push payload, never
// touches the network and shows only texts from the table it was built with.
import { fail, pass, PUSH_LIMITS, type PushResult } from './limits.ts';

export interface WorkerText {
  readonly title: string;
  readonly body: string;
}

export interface WorkerOptions {
  /** Texts by language (`^[a-z]{2,3}$`); the worker takes the primary subtag of `navigator.language`. */
  readonly texts: Readonly<Record<string, WorkerText>>;
  /** The language used when the browser's is not in the table; must be in it. */
  readonly fallback: string;
  /** Where a click goes: an absolute https URL without fragment, or a path starting with one `/`. */
  readonly appUrl: string;
  /** Notifications with the same tag replace each other (`^[A-Za-z0-9._-]{1,64}$`). */
  readonly tag: string;
  /** Optional icon and badge URLs (same form as `appUrl`). */
  readonly icon?: string;
  readonly badge?: string;
}

export type WorkerRefusal = 'options' | 'texts' | 'language' | 'text' | 'fallback' | 'url' | 'tag';

const LANGUAGE = /^[a-z]{2,3}$/;
const TAG = /^[A-Za-z0-9._-]{1,64}$/;
const FORBIDDEN_IN_TEXT = /[\p{Cc}\p{Cf}\p{Cs}\p{Zl}\p{Zp}]/u;
const URL_FORM =
  /^(?:https:\/\/[A-Za-z0-9.-]+(?::[0-9]{1,5})?(?:\/[\x21-\x22\x24-\x7e]*)?|\/(?!\/)[\x21-\x22\x24-\x7e]*)$/;

/** Text for a notification: printable, no control, format, surrogate or line separator character. */
const isText = (v: unknown, max: number): v is string =>
  typeof v === 'string' && v.length >= 1 && v.length <= max && !FORBIDDEN_IN_TEXT.test(v);

/** `#` is excluded from URL_FORM (fragment), the rest is plain printable ASCII. */
const isUrl = (v: unknown): v is string =>
  typeof v === 'string' && v.length <= PUSH_LIMITS.workerUrlMax && URL_FORM.test(v);

const isPlainObject = (v: unknown): v is Record<string, unknown> =>
  typeof v === 'object' &&
  v !== null &&
  !Array.isArray(v) &&
  (Object.getPrototypeOf(v) === Object.prototype || Object.getPrototypeOf(v) === null);

/** A JSON text that is also safe as the body of a script (no line separator characters, no `</`). */
const SEPARATORS = new RegExp(
  '[' + String.fromCharCode(0x2028) + String.fromCharCode(0x2029) + ']',
  'g',
);
const BACKSLASH_U = String.fromCharCode(92) + 'u';
const literal = (value: unknown): string =>
  JSON.stringify(value)
    .replace(SEPARATORS, (c) => BACKSLASH_U + c.charCodeAt(0).toString(16))
    .replace(/</g, BACKSLASH_U + '003c');

/** The script. `__CONFIG__` is replaced by the validated table. */
const TEMPLATE = `'use strict';
// Generated by device-sync (push layer). Content-free push: the payload is never read.
const CONFIG = __CONFIG__;

function pickText() {
  const language = String((self.navigator && self.navigator.language) || '')
    .toLowerCase()
    .split('-')[0];
  const key = Object.prototype.hasOwnProperty.call(CONFIG.texts, language) ? language : CONFIG.fallback;
  return CONFIG.texts[key];
}

function appBase() {
  return new URL(CONFIG.appUrl, self.location.href);
}

function isApp(clientUrl) {
  let url;
  const base = appBase();
  try {
    url = new URL(clientUrl);
  } catch (e) {
    return false;
  }
  if (url.origin !== base.origin) return false;
  const prefix = base.pathname.endsWith('/') ? base.pathname : base.pathname + '/';
  return url.pathname === base.pathname || url.pathname.startsWith(prefix);
}

self.addEventListener('push', function (event) {
  const text = pickText();
  const options = { body: text.body, tag: CONFIG.tag, renotify: true };
  if (CONFIG.icon) options.icon = CONFIG.icon;
  if (CONFIG.badge) options.badge = CONFIG.badge;
  event.waitUntil(self.registration.showNotification(text.title, options));
});

self.addEventListener('notificationclick', function (event) {
  event.notification.close();
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then(function (list) {
      for (const client of list) {
        if (isApp(client.url) && typeof client.focus === 'function') return client.focus();
      }
      return self.clients.openWindow(appBase().href);
    }),
  );
});
`;

/** The source of the service worker, or a code. Every text, URL and the tag is checked. */
export function buildServiceWorkerSource(
  options: WorkerOptions,
): PushResult<string, WorkerRefusal> {
  try {
    if (!isPlainObject(options)) return fail('options');
    const { texts, fallback, appUrl, tag, icon, badge } = options;
    if (!isPlainObject(texts)) return fail('texts');
    const languages = Object.keys(texts);
    if (languages.length < 1 || languages.length > PUSH_LIMITS.workerLanguagesMax)
      return fail('texts');
    const table: Record<string, WorkerText> = Object.create(null) as Record<string, WorkerText>;
    for (const language of languages.sort()) {
      if (!LANGUAGE.test(language)) return fail('language');
      const entry: unknown = texts[language];
      if (!isPlainObject(entry)) return fail('text');
      const keys = Object.keys(entry);
      if (keys.length !== 2 || !keys.includes('title') || !keys.includes('body'))
        return fail('text');
      if (!isText(entry['title'], PUSH_LIMITS.workerTitleMax)) return fail('text');
      if (!isText(entry['body'], PUSH_LIMITS.workerBodyMax)) return fail('text');
      table[language] = { title: entry['title'], body: entry['body'] };
    }
    if (typeof fallback !== 'string' || !Object.hasOwn(table, fallback)) return fail('fallback');
    if (!isUrl(appUrl)) return fail('url');
    if (icon !== undefined && !isUrl(icon)) return fail('url');
    if (badge !== undefined && !isUrl(badge)) return fail('url');
    if (typeof tag !== 'string' || !TAG.test(tag)) return fail('tag');
    const config: Record<string, unknown> = { texts: { ...table }, fallback, appUrl, tag };
    if (icon !== undefined) config['icon'] = icon;
    if (badge !== undefined) config['badge'] = badge;
    return pass(TEMPLATE.replace('__CONFIG__', () => literal(config)));
  } catch {
    return fail('options');
  }
}
